"""Build the bundled Bangumi episode index from a pinned local release."""

import argparse
from collections import Counter
import gzip
import hashlib
import json
from pathlib import Path
import struct


SOURCE_COMMIT = 'e6d78b44cfc999eacabc28fa0661f9dee743de79'
MANIFEST_SHA256 = 'eb8a6c2829ec3d1e9e7aed8837ca24f08f21fd2b5df788bb67b4d863550ece35'
ASSETS = {
    'subjects': ('d97537c6d78249a3d1c61cead590b1b742f0768e8000cdced1379a8dca2c8e7b', 20_379),
    'episodes': ('eea690afb41c753c810878c6ddc8c9fef8fc864fa106a99ebe189f003cfbb0d8', 212_241),
}
MAXIMUM_ROWS = 250_000
INT32_MAXIMUM = (1 << 31) - 1
FORMAT_MAGIC = b'BTM1'
ROW = struct.Struct('<5i')
RESOURCE = Path(__file__).resolve().parents[1] / 'src/Momoka.Core/Scrobbling/BangumiTmdbMap.bin.gz'


def read_verified(path, sha256):
    data = path.read_bytes()
    if hashlib.sha256(data).hexdigest() != sha256:
        raise ValueError(f'{path.name} differs from the pinned SHA-256')
    return json.loads(data)


def read_source(source):
    manifest = read_verified(source / 'manifest.json', MANIFEST_SHA256)
    if manifest['schemaVersion'] != 1 or manifest['sourceCommit'] != SOURCE_COMMIT or manifest['sourceDirty']:
        raise ValueError('unexpected upstream manifest')
    for kind, (sha256, count) in ASSETS.items():
        name = f'{kind}.json'
        if manifest['files'][name]['sha256'] != sha256 or manifest['counts'][kind] != count:
            raise ValueError(f'unexpected manifest entry for {name}')
        asset = read_verified(source / name, sha256)
        if asset['schemaVersion'] != 1 or not isinstance(asset[kind], list) or len(asset[kind]) != count:
            raise ValueError(f'unexpected shape or row count in {name}')
        yield asset[kind]


def number(value, minimum=1):
    if type(value) is not int or not minimum <= value <= INT32_MAXIMUM:
        raise ValueError('expected an Int32 identifier or coordinate')
    return value


def targets(row):
    if not isinstance(row['targets'], list) or not row['targets']:
        raise ValueError('expected a non-empty list of mapping targets')
    for target in row['targets']:
        if target['type'] not in ('tv', 'movie'):
            raise ValueError('unknown TMDB media type')
        yield target


def make_index(subjects, episodes):
    subject_ids = set()
    known_series = set()
    for row in subjects:
        subject = number(row['bangumiId'])
        if subject in subject_ids:
            raise ValueError('repeated Bangumi subject row')
        subject_ids.add(subject)
        known_series.update(number(target['id']) for target in targets(row) if target['type'] == 'tv')

    by_coordinate = {}
    source_targets = Counter()
    for row in episodes:
        subject = number(row['bangumiId'])
        bangumi_episode = number(row['bangumiEpisodeId'])
        if subject not in subject_ids:
            raise ValueError('episode refers to an unknown Bangumi subject')
        for target in targets(row):
            tmdb = number(target['id'])
            if target['type'] == 'movie':
                source_targets[bangumi_episode] += 1
                continue
            coordinate = (tmdb, number(target['season'], minimum=0), number(target['episode']))
            known_series.add(tmdb)
            links = by_coordinate.setdefault(coordinate, set())
            link = (subject, bangumi_episode)
            if link not in links:
                links.add(link)
                source_targets[bangumi_episode] += 1

    # Count all targets (including movies) before filtering cross-namespace and multi-episode links.
    safe_rows = [
        (*coordinate, *link)
        for coordinate, links in by_coordinate.items() if len(links) == 1
        for link in links if source_targets[link[1]] == 1
    ]
    rows = sorted([*safe_rows, *((tmdb, 0, 0, 0, 0) for tmdb in known_series)])
    if not 0 < len(rows) <= MAXIMUM_ROWS:
        raise ValueError('unexpected output row count')
    return rows, len(known_series), len(by_coordinate) - len(safe_rows)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('source', type=Path, help='directory holding the pinned manifest.json, subjects.json and episodes.json')
    parser.add_argument('--output', type=Path, default=RESOURCE)
    parser.add_argument('--check', action='store_true', help='compare the generated bytes without writing the resource')
    args = parser.parse_args()
    try:
        rows, series_count, rejected = make_index(*read_source(args.source))
        plain = FORMAT_MAGIC + struct.pack('<i', len(rows)) + b''.join(ROW.pack(*row) for row in rows)
        compressed = gzip.compress(plain, compresslevel=9, mtime=0)
        # Use the portable OS marker even on Python versions that copy it from zlib when mtime=0.
        compressed = compressed[:9] + b'\xff' + compressed[10:]
        if args.check:
            if args.output.read_bytes() != compressed:
                raise ValueError('generated resource differs')
        else:
            args.output.write_bytes(compressed)
    except (OSError, ValueError, KeyError, TypeError) as error:
        parser.exit(1, f'{error}\n')
    print(f'{series_count} series, {len(rows) - series_count} episodes, {rejected} ambiguous coordinates omitted')
    print(f'{len(compressed)} bytes, SHA-256 {hashlib.sha256(compressed).hexdigest()}')


if __name__ == '__main__':
    main()
